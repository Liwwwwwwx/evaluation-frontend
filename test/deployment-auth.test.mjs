import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { NextRequest } = require('next/server');
const output = ts.transpileModule(fs.readFileSync(new URL('../src/lib/evaluation-auth-proxy.ts', import.meta.url), 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const mod = { exports: {} };
new Function('require', 'module', 'exports', output)(require, mod, mod.exports);
const { backendOrigin, proxyEvaluationAuth } = mod.exports;
test('生产代理仅允许回环 HTTP，HTTP Cookie 需要显式配置且同源校验保留', async t => {
  const previous = { ...process.env }; const originalFetch = globalThis.fetch;
  t.after(() => { process.env = previous; globalThis.fetch = originalFetch; });
  process.env.NODE_ENV = 'production'; process.env.SCIENCE_EVALUATION_BACKEND_URL = 'http://127.0.0.1:7714';
  assert.equal(backendOrigin(), 'http://127.0.0.1:7714');
  process.env.SCIENCE_EVALUATION_BACKEND_URL = 'http://192.0.2.1:7714'; assert.throws(() => backendOrigin());
  process.env.SCIENCE_EVALUATION_BACKEND_URL = 'http://127.0.0.1:7714';
  let calls = 0;
  globalThis.fetch = async () => { calls++; return new Response('{}', { headers: { 'Set-Cookie': 'evaluation_session=testsession; HttpOnly; SameSite=Lax' } }); };
  const request = (origin, header = origin) => new NextRequest(`${origin}/api/auth/login`, { method: 'POST', headers: { host: new URL(origin).host, origin: header, 'Content-Type': 'application/json' }, body: JSON.stringify({ username: 'test', password: 'example' }) });
  delete process.env.EVALUATION_ALLOW_HTTP;
  assert.match((await proxyEvaluationAuth(request('http://192.0.2.1:6714'), 'login')).headers.get('set-cookie'), /Secure/);
  process.env.EVALUATION_ALLOW_HTTP = 'true';
  assert.doesNotMatch((await proxyEvaluationAuth(request('http://192.0.2.1:6714'), 'login')).headers.get('set-cookie'), /Secure/);
  assert.match((await proxyEvaluationAuth(request('https://example.com'), 'login')).headers.get('set-cookie'), /Secure/);
  assert.equal((await proxyEvaluationAuth(request('http://192.0.2.1:6714', 'http://other.example'), 'login')).status, 403);
  assert.equal(calls, 3);
});
